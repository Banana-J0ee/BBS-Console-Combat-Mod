#!/usr/bin/env python3
"""genorbtex.py -> src/orbtex_gen.h

KH2's MP orb bubble, for the SP orbs (sporb.c).  KH2 draws its MP orbs with the bubble of obj/PRIZE.mdlx's second
texture (remastered: a 256x128 DXT5; the bubble fills the left 128x128), tinted blue.  BBS's small D-Link prize
(ANM 0xa4 of resident.frr) draws two cells of shared texture 0x12: the solid star (u 0-0.25, v 0.5-1, normal
blending) and a white star under it as a pulsing glow (u 0.25-0.5, v 0.5-1, additive, tinted by the parts).  The
orb's texture keeps that layout: the bubble, tinted blue, in the first cell and a soft round glow in the second;
everything else is clear (so the prize's sparkles, which sample another texture's u .13-.25 / v 0-.12, vanish).
The glow cell is clear too: the D-Link prize's glow parts draw nothing on an orb.

Output: the two 64x64 cells as RGBA rows; sporb.c places them in a 256x128 texture.

Input (your own game file, extracted with the scripts in tools/):
    KH2_PRIZE_DDS   remastered texture 1 of KH2's obj/PRIZE.mdlx (256x128)
"""
import os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = Image.open(os.environ['KH2_PRIZE_DDS']).convert('RGBA')
assert src.size == (256, 128), src.size
C = 64                                   # cell size in the 256x128 texture
TINT = np.array([0.42, 0.70, 1.00])      # KH2's MP orb blue

# the bubble: its bounding box, square, scaled into the cell with a 2-pixel margin
a = np.array(src)
ys, xs = np.nonzero(a[:, :128, 3] > 8)
x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
s = max(x1 - x0, y1 - y0); cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
box = (cx - s // 2, cy - s // 2, cx - s // 2 + s, cy - s // 2 + s)
# filter on premultiplied alpha so the edge does not pick up the clear pixels' colour
f = a.astype(np.float32); f[..., :3] *= f[..., 3:4] / 255.0
chans = [np.array(Image.fromarray(f[..., c]).crop(box).resize((C - 4, C - 4), Image.LANCZOS)) for c in range(4)]
b = np.clip(np.stack(chans, axis=2), 0, 255)
rgb = np.where(b[..., 3:4] > 0, b[..., :3] / np.maximum(b[..., 3:4], 1e-3) * 255.0, 0)
lum = rgb.mean(axis=2, keepdims=True) / 255.0
# blue body, highlights kept white (the brightest part of the bubble is its shine)
shine = np.clip((lum - 0.75) / 0.25, 0, 1)
col = (lum * TINT * 1.15 * (1 - shine) + shine) * 255.0
bub = np.zeros((C, C, 4), np.float32)
bub[2:C - 2, 2:C - 2, :3] = np.clip(col, 0, 255)
bub[2:C - 2, 2:C - 2, 3] = np.clip(b[..., 3] * 1.35, 0, 255)

# the glow cell: clear (2026-10-23, asked for: the D-Link prize's pulsing additive glow showed as a shine inside the
# bubble; KH2's MP orb has none)
glow = np.zeros((C, C, 4), np.float32)

def arr(name, cell):
    flat = np.round(cell).astype(np.uint8).reshape(-1)
    rows = ['    ' + ''.join('%d,' % v for v in flat[i:i + 32]) for i in range(0, len(flat), 32)]
    return 'static const u8 %s[%d * %d * 4] = {\n%s\n};\n' % (name, C, C, '\n'.join(rows))

out = ['/* generated by tools/genorbtex.py - KH2 obj/PRIZE.mdlx texture 1 (the MP orb bubble), tinted blue (the glow cell clear) */\n',
       '#define ORBTEX_CELL %d\n' % C, '#ifdef ORBTEX_DATA\n', arr('orbtex_bubble', bub), arr('orbtex_glow', glow), '#endif\n']
open(os.path.join(ROOT, 'src', 'orbtex_gen.h'), 'w').write(''.join(out))
if os.environ.get('ORBTEX_PREVIEW'):
    sheet = np.zeros((128, 256, 4), np.uint8)
    sheet[64:128, 0:64] = np.round(bub); sheet[64:128, 64:128] = np.round(glow)
    Image.fromarray(sheet).save(os.environ['ORBTEX_PREVIEW'])
print('orbtex_gen.h written')
