#!/usr/bin/env python3
"""genorbse.py -> src/orbse_gen.h

KH2's MP orb pickup sound, for the SP orbs (sporb.c).  KH2 plays it from its prize table (kinds 5 / 6, the MP orbs:
SE id 17 = sound 17 of se/se000.win32.scd, the common SE bank; HP orbs are 16, munny 15).  Sound 17 is one track
(16: KeyOn, wait 462 ms, KeyOff) of one audio entry (167: MS-ADPCM, mono, 47978 Hz, 0.46 s).  The track and the
audio entry are copied out as they are; sporb.c adds them to BBS's own common SE bank as it is loaded.

Input (your own game file, extracted with the scripts in tools/):
    KH2_SE000   se/se000.win32.scd of KH2 (kh2_*.hed)
"""
import os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.environ['KH2_SE000'], 'rb').read()
assert d[:8] == b'SEDBSSCF'
ns, nt, na = struct.unpack_from('<3H', d, 0x30)
to, ao = struct.unpack_from('<2I', d, 0x38)
S = struct.unpack_from('<%dI' % ns, d, 0x50)
T = struct.unpack_from('<%dI' % nt, d, to)
A = struct.unpack_from('<%dI' % na, d, ao)

# sound 17: one track; its {track, audio} pair ends the (version 4) entry
s = S[17]
assert d[s] == 1 and struct.unpack_from('<I', d, s + 0xc)[0] == 17
track, audio = struct.unpack_from('<HH', d, S[18] - 4)
assert (track, audio) == (16, 167), (track, audio)

tb = d[T[track]:T[track + 1]]
assert tb.endswith(b'\x0c\x00\x00\x00') and len(tb) == 88
sz, ch, rate, codec, ls, le, ex, aux = struct.unpack_from('<8I', d, A[audio])
assert codec == 12 and ch == 1
ab = bytearray(d[A[audio]:A[audio] + 0x20 + ex + sz])
struct.pack_into('<I', ab, 0x1c, 0)          # no aux chunks (v4 keeps flags in the top byte)

def arr(name, b):
    rows = ['    ' + ''.join('0x%02x,' % x for x in b[i:i + 24]) for i in range(0, len(b), 24)]
    return 'static const u8 %s[%d] = {\n%s\n};\n' % (name, len(b), '\n'.join(rows))

out = ['/* generated by tools/genorbse.py - KH2 se000 sound 17 (the MP orb pickup): track %d, audio %d (%d Hz, %d ms) */\n'
       % (track, audio, rate, struct.unpack_from('<I', tb, len(tb) - 8)[0])]
out.append('#ifdef ORBSE_DATA\n')
out.append(arr('orbse_track', tb))
out.append(arr('orbse_audio', ab))
out.append('#endif\n')
open(os.path.join(ROOT, 'src', 'orbse_gen.h'), 'w').write(''.join(out))
print('orbse_gen.h: track', len(tb), 'audio', len(ab))
