#!/usr/bin/env python3
"""Generate src/steals_gen.h: the bytes each hook overwrites (needs the unmodified game exe, BBS_EXE)."""
import os
from bbsexe import ROOT
from steal import steal,raw
S=[ # (name, rva, minlen)  relocatable steals (function entries)
 ('S_gauge_init',0x208d90,5),('S_gauge_update',0x209c40,5),('S_gauge_dtor',0x207dc0,5),
 ('S_dlink_open',0x2385c0,5),('S_dlink_pick',0x205c00,5),
 ('S_item_effect',0x262200,5),('S_pd_init',0x2854a0,5),
 ('S_deck_input',0x233720,5),('S_confirm',0x272580,5),
 ('S_style_decide',0x236612,5),
 # style.c: the start of a style change (28a950) asks "in the air?" (264a10) before choosing to fall first
 ('S_style_air',0x28a942,5),
 # speed.c: the "has this action ended?" tests of the action states, and the fall-loop hover test
 ('S_atk_end',0x228edf,8),('S_mag_anim',0x267f7f,5),('S_mag_lock',0x267faa,8),
 ('S_deck_a',0x2243e0,8),('S_deck_b',0x224196,8),('S_deck_c',0x22511f,8),
 ('S_item_end',0x261d76,8),('S_friend_end',0x2596cb,8),('S_fin_end',0x255fdc,8),
 ('S_fall_hover',0x26311f,6),
 # speed.c: the combo table's conditions are built (2239b0): "target above" for the launcher
 ('S_launch',0x22382d,5),
 # status.c: Destroy(instance handle) of the 2D-layout runtime
 ('S_l2d_destroy',0x1a5690,5),
 # speed.c: a MOVE command starts (2430c0 in Steam: slide, dodge, Air Slide ...) - Terra's Air Slide cooldown
 ('S_move_start',0x242de0,5),
]
R=[('S_gravity',0x21c875,5)]   # never executed: the handler always redirects
out=['/* generated by gensteal.py */']
for n,a,m in S: out.append(steal(n,a,m))
for n,a,m in R: out.append(raw(n,a,m))
open(os.path.join(ROOT,'src','steals_gen.h'),'w').write('\n'.join(out)+'\n')
print('%d hook sites written to src/steals_gen.h'%(len(S)+len(R)))
